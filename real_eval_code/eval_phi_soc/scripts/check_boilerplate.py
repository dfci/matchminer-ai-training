#!/usr/bin/env python3
"""
LLM-based boilerplate exclusion checking for patient-trial matches (SOC evaluation).

This script checks if patients meet common exclusion criteria ("boilerplate" criteria)
such as uncontrolled brain metastases, renal dysfunction, etc.

Two modes:
- "patient_centric": Check boilerplate for patient-centric candidates
- "trial_centric": Check boilerplate for trial-centric candidates

Usage:
    python check_boilerplate.py --gpu 0 --mode patient_centric
    python check_boilerplate.py --gpu 0 --mode trial_centric
    python check_boilerplate.py --gpu 0 --mode patient_centric --input ./custom_candidates.csv
"""

import argparse
import os
import sys
import glob
import pandas as pd
from pathlib import Path

# Repo root for default paths
REPO_ROOT = Path(__file__).resolve().parents[3]  # matchminer-ai-training


def parse_args():
    parser = argparse.ArgumentParser(description="LLM-based boilerplate exclusion checking")
    parser.add_argument("--gpu", type=str, required=True,
                        help="GPU ID to use (e.g., '0')")
    parser.add_argument("--mode", type=str, required=True,
                        choices=["patient_centric", "trial_centric"],
                        help="Check mode: 'patient_centric' or 'trial_centric'")
    parser.add_argument("--input", type=str, default=None,
                        help="Input CSV file with candidates (default: derived from mode)")
    parser.add_argument("--output-dir", type=str, default=None,
                        help="Output directory for shard files (default: derived from mode)")
    parser.add_argument("--batch-size", type=int, default=2000,
                        help="Batch size for LLM inference")
    parser.add_argument("--model", type=str, default='openai/gpt-oss-120b',
                        help="Model path (default: openai/gpt-oss-120b")
    parser.add_argument("--download-dir", type=str,
                        default="/data1/ken/meta/2024/meta_ai",
                        help="Download directory for model weights (used if model not found locally)")
    parser.add_argument("--gpu-mem-util", type=float, default=0.94,
                        help="GPU memory utilization")
    parser.add_argument("--max-model-len", type=int, default=10000,
                        help="Maximum model context length")
    return parser.parse_args()


def ask_about_boilerplate(patient_boilerplates, trial_boilerplates, llama_model):
    """Ask LLM whether patients are excluded by boilerplate criteria."""
    from vllm import SamplingParams

    tokenizer = llama_model.get_tokenizer()
    prompts = []

    for patient_boilerplate, trial_boilerplate in zip(patient_boilerplates, trial_boilerplates):
        messages = [
            {'role': 'system', 'content': "Reasoning: high"},
            {'role': 'user', 'content': (
                "You are a brilliant oncologist with encyclopedic knowledge about cancer and its treatment.\n"
                "Your job is to evaluate whether a patient has any underlying medical conditions that would exclude him or her from a specific clinical trial.\n\n"
                f"Here is an extract of the patient's history:\n{patient_boilerplate}\n"
                f"Here are the exclusion criteria for the trial:\n{trial_boilerplate}\n"
                "Note that the extract was generated by prompting an LLM to determine whether the patient meets specific common exclusion criteria, "
                "such as uncontrolled brain metastases, lack of measurable disease, congestive heart failure, pneumonitis, renal dysfunction, "
                "liver dysfunction, and HIV or hepatitis infection, and to present evidence for whether the patient met the criterion.\n"
                "You should therefore not assume that mention of such condition means the patient has the condition; it may represent the LLM reasoning "
                "about whether the patient has the condition.\n"
                "Based on the extract, you should determine whether the patient clearly meets one of the exclusion criteria for this specific trial.\n"
                "Do not evaluate exclusion criteria other than those listed for this trial.\n"
                "Reason through one exclusion criterion at a time. Generate a numbered list of the criteria as you go. For each one, decide whether the patient clearly "
                "meets the exclusion criteron. If it is not completely clear that the patient meets the exclusion criterion, give the patient the benefit of the doubt, "
                "and err on the side of deciding the patient is not excluded. A description in the patient extract that a condition is mild, low-grade, or resolved is even "
                "more of a reason not to exclude the patient based on that condition.\n"
                'Once you have evaluated all exclusion criteria, answer the question "Is this patient clearly excluded from this trial?" with a one-word "Yes!" or "No!" answer, '
                "based on whether the patient clearly met any of the individual exclusion criteria. It is critical that your final word be either \"Yes!\" or \"No!\", verbatim, and case-sensitive.\n"
                "Make sure to include the exclamation point in your final one-word answer.\n"
                "No introductory text or concluding text after that final answer."
            )}
        ]

        prompt = tokenizer.apply_chat_template(
            conversation=messages, add_generation_prompt=True, tokenize=False
        )
        prompts.append(prompt)

    responses = llama_model.generate(
        prompts,
        SamplingParams(
            temperature=0.0,
            top_k=1,
            max_tokens=7500,
            repetition_penalty=1.2,
        )
    )

    response_texts = [x.outputs[0].text for x in responses]
    exclusion_results = []

    for response_text in response_texts:
        if ("Yes!" in response_text[-10:]) or ("YES!" in response_text[-10:]):
            exclusion_results.append(1.0)
        else:
            exclusion_results.append(0.0)

    return responses, response_texts, exclusion_results


def get_completed_batches(output_dir):
    """Get the highest completed batch index."""
    pattern = os.path.join(output_dir, "*_through_*.csv")
    files = glob.glob(pattern)
    max_idx = -1
    for f in files:
        try:
            basename = os.path.basename(f)
            idx_str = basename.split("_through_")[1].replace(".csv", "")
            idx = int(idx_str)
            max_idx = max(max_idx, idx)
        except:
            pass
    return max_idx


def main():
    args = parse_args()

    # Set defaults based on mode
    if args.model is None:
        args.model = 'openai/gpt-oss-120b'

    if args.input is None:
        if args.mode == "patient_centric":
            args.input = str(REPO_ROOT.parent / "data/phi_soc/patient_centric_candidates.csv")
        else:
            args.input = str(REPO_ROOT.parent / "data/phi_soc/trial_centric_candidates.csv")

    if args.output_dir is None:
        if args.mode == "patient_centric":
            args.output_dir = str(REPO_ROOT.parent / "data/phi_soc/patient_centric_boilerplate_checks")
        else:
            args.output_dir = str(REPO_ROOT.parent / "data/phi_soc/trial_centric_boilerplate_checks")

    # Set GPU
    os.environ['CUDA_VISIBLE_DEVICES'] = args.gpu

    from vllm import LLM

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load input data
    print(f"Loading input from {args.input}...")
    candidates = pd.read_csv(args.input)
    print(f"Loaded {candidates.shape[0]} candidate pairs")

    # Initialize LLM
    print(f"Initializing LLM from {args.model}...")
    llm = LLM(
        model=args.model,
        tensor_parallel_size=1,
        download_dir=args.download_dir,
        gpu_memory_utilization=args.gpu_mem_util,
        max_model_len=args.max_model_len
    )

    # Check for resume point
    last_completed = get_completed_batches(str(output_dir))
    start_idx = last_completed + 1 if last_completed >= 0 else 0
    print(f"Starting from index {start_idx}")

    # Process in batches
    batch_list = []
    num_in_batch = 0

    for i in range(start_idx, candidates.shape[0]):
        batch_list.append(candidates.iloc[[i]])
        num_in_batch += 1

        if (num_in_batch == args.batch_size) or (i == (candidates.shape[0] - 1)):
            output = pd.concat(batch_list, axis=0)

            _, output['llm_boilerplate_response'], output['exclusion_result'] = ask_about_boilerplate(
                output['patient_boilerplate_text'].astype(str).tolist(),
                output['trial_boilerplate_text'].astype(str).tolist(),
                llm
            )

            # Determine output filename based on mode
            if args.mode == "patient_centric":
                output_file = output_dir / f"patient_centric_boilerplate_through_{i}.csv"
            else:
                output_file = output_dir / f"trial_centric_boilerplate_through_{i}.csv"

            output.to_csv(str(output_file), index=False)
            print(f"Saved batch through {i}")

            num_in_batch = 0
            batch_list = []

    print("\n=== Done ===")


if __name__ == "__main__":
    main()
